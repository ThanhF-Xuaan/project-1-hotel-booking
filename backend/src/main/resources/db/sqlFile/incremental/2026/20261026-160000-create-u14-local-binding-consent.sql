-- U14 local v1 only. Real customer identity binding is outside this contract.

CREATE TABLE IF NOT EXISTS personalization_account_bindings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issuer VARCHAR(512) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    guest_id BIGINT NOT NULL REFERENCES booking_guests(id) ON DELETE RESTRICT,
    binding_version BIGINT NOT NULL CHECK (binding_version > 0),
    source VARCHAR(50) NOT NULL DEFAULT 'SYNTHETIC_FIXTURE'
        CHECK (source = 'SYNTHETIC_FIXTURE'),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'REVOKED')),
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_personalization_binding_issuer_nonblank CHECK (btrim(issuer) <> ''),
    CONSTRAINT chk_personalization_binding_subject_nonblank CHECK (btrim(subject) <> ''),
    CONSTRAINT chk_personalization_binding_lifecycle CHECK (
        (status = 'ACTIVE' AND revoked_at IS NULL)
        OR (status = 'REVOKED' AND revoked_at IS NOT NULL)
    ),
    CONSTRAINT uq_personalization_binding_subject_version UNIQUE (issuer, subject, binding_version),
    CONSTRAINT uq_personalization_binding_id_version UNIQUE (id, binding_version)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_personalization_binding_active_subject
    ON personalization_account_bindings (issuer, subject)
    WHERE status = 'ACTIVE';

CREATE UNIQUE INDEX IF NOT EXISTS uq_personalization_binding_active_guest
    ON personalization_account_bindings (guest_id)
    WHERE status = 'ACTIVE';

CREATE INDEX IF NOT EXISTS idx_personalization_binding_guest
    ON personalization_account_bindings (guest_id);

DROP TRIGGER IF EXISTS trg_personalization_binding_updated_at ON personalization_account_bindings;
CREATE TRIGGER trg_personalization_binding_updated_at
    BEFORE UPDATE ON personalization_account_bindings
    FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

CREATE TABLE IF NOT EXISTS personalization_consents (
    binding_id BIGINT NOT NULL REFERENCES personalization_account_bindings(id) ON DELETE RESTRICT,
    hotel_id SMALLINT NOT NULL REFERENCES hotels(id) ON DELETE RESTRICT,
    purpose VARCHAR(50) NOT NULL CHECK (purpose = 'ROOM_TYPE_RECOMMENDATION'),
    granted BOOLEAN NOT NULL,
    revision BIGINT NOT NULL CHECK (revision >= 1),
    policy_version VARCHAR(100),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_personalization_consent_policy_nonblank
        CHECK (policy_version IS NULL OR btrim(policy_version) <> ''),
    CONSTRAINT chk_personalization_consent_grant_policy
        CHECK (NOT granted OR policy_version IS NOT NULL),
    CONSTRAINT pk_personalization_consents PRIMARY KEY (binding_id, hotel_id, purpose)
);

CREATE INDEX IF NOT EXISTS idx_personalization_consents_hotel
    ON personalization_consents (hotel_id);

DROP TRIGGER IF EXISTS trg_personalization_consent_updated_at ON personalization_consents;
CREATE TRIGGER trg_personalization_consent_updated_at
    BEFORE UPDATE ON personalization_consents
    FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

CREATE TABLE IF NOT EXISTS personalization_consent_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    binding_id BIGINT NOT NULL,
    binding_version BIGINT NOT NULL CHECK (binding_version > 0),
    hotel_id SMALLINT NOT NULL REFERENCES hotels(id) ON DELETE RESTRICT,
    purpose VARCHAR(50) NOT NULL CHECK (purpose = 'ROOM_TYPE_RECOMMENDATION'),
    revision BIGINT NOT NULL CHECK (revision >= 1),
    granted BOOLEAN NOT NULL,
    policy_version VARCHAR(100),
    event_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_personalization_event_policy_nonblank
        CHECK (policy_version IS NULL OR btrim(policy_version) <> ''),
    CONSTRAINT chk_personalization_event_grant_policy
        CHECK (NOT granted OR policy_version IS NOT NULL),
    CONSTRAINT fk_personalization_event_binding_version
        FOREIGN KEY (binding_id, binding_version)
        REFERENCES personalization_account_bindings(id, binding_version) ON DELETE RESTRICT,
    CONSTRAINT uq_personalization_consent_event_revision
        UNIQUE (binding_id, hotel_id, purpose, revision)
);

CREATE INDEX IF NOT EXISTS idx_personalization_consent_events_binding_version
    ON personalization_consent_events (binding_id, binding_version);

CREATE INDEX IF NOT EXISTS idx_personalization_consent_events_hotel
    ON personalization_consent_events (hotel_id);

COMMENT ON TABLE personalization_account_bindings IS
    'U14 local v1 synthetic-only Keycloak issuer/subject to booking guest bindings.';
COMMENT ON TABLE personalization_consents IS
    'Current U14 local v1 room recommendation consent; revision zero is represented by no row.';
COMMENT ON TABLE personalization_consent_events IS
    'Append-only U14 local v1 grant/revoke evidence; application code must not update or delete rows.';
